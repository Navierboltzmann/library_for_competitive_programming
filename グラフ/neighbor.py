"""
グリッドの4近傍

H 行 W 列のグリッドで, マス (x, y) に上下左右で隣接するマスを列挙する.
盤面サイズは引数 h, w で渡すか, 省略してグローバル変数 H, W を使う (従来通り).

使用例:
    H, W = 3, 4
    nb(0, 0)          # -> [(1, 0), (0, 1)]
    nb(1, 1, 3, 4)    # -> [(2, 1), (0, 1), (1, 2), (1, 0)]
"""


def nb(x, y, h=None, w=None):
    """
    マス (x, y) の4近傍のうちグリッド内にあるものを返す.

    x: 行 (0 <= x < h), y: 列 (0 <= y < w)
    h, w: グリッドの行数・列数 (省略時はグローバル変数 H, W)
    戻り値: [(x+1, y), (x-1, y), (x, y+1), (x, y-1)] のうちグリッド内のもの (この順)
    計算量: O(1)
    """
    if h is None:
        h = H
    if w is None:
        w = W
    tmp = []
    if x + 1 < h:
        tmp.append((x + 1, y))
    if x >= 1:
        tmp.append((x - 1, y))
    if y + 1 < w:
        tmp.append((x, y + 1))
    if y >= 1:
        tmp.append((x, y - 1))
    return tmp


if __name__ == "__main__":
    H, W = 3, 4
    print(nb(0, 0))  # [(1, 0), (0, 1)]
    print(nb(1, 1, 3, 4))  # [(2, 1), (0, 1), (1, 2), (1, 0)]
